-- ---------------------------------------------------------------------
-- 17a. RISK_SCORE_HISTORY - one snapshot per policy per day
-- The composite primary key makes a second same-day snapshot impossible.
-- ---------------------------------------------------------------------
CREATE TABLE risk_score_history (
    snapshot_date  DATE         NOT NULL,
    policy_id      VARCHAR2(20) NOT NULL
                   CONSTRAINT rsh_policy_fk REFERENCES policies (policy_id),
    risk_score     NUMBER(3),
    risk_band      VARCHAR2(10),
    CONSTRAINT risk_score_history_pk PRIMARY KEY (snapshot_date, policy_id)
);


-- ---------------------------------------------------------------------
-- 17b. COLLECTION_ALERTS - items the batch wants a human to review
-- ---------------------------------------------------------------------
CREATE TABLE collection_alerts (
    alert_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                     CONSTRAINT collection_alerts_pk PRIMARY KEY,
    policy_id        VARCHAR2(20) NOT NULL
                     CONSTRAINT cal_policy_fk REFERENCES policies (policy_id),
    alert_type       VARCHAR2(30) NOT NULL
                     CONSTRAINT cal_type_chk CHECK (alert_type IN ('NEW_HIGH_RISK','PROMISE_BROKEN')),
    alert_text       VARCHAR2(500),
    status           VARCHAR2(20) DEFAULT ON NULL 'OPEN' NOT NULL
                     CONSTRAINT cal_status_chk CHECK (status IN ('OPEN','ACKNOWLEDGED')),
    created_on       DATE DEFAULT ON NULL SYSDATE NOT NULL,
    acknowledged_by  VARCHAR2(255),
    acknowledged_on  DATE
);


-- ---------------------------------------------------------------------
-- 17c. Function-based unique index: one OPEN alert per policy and type,
-- unlimited acknowledged history. For acknowledged rows both expressions
-- are NULL, and Oracle doesn't index all-NULL keys.
-- ---------------------------------------------------------------------
CREATE UNIQUE INDEX collection_alerts_open_uk ON collection_alerts (
    CASE WHEN status = 'OPEN' THEN policy_id  END,
    CASE WHEN status = 'OPEN' THEN alert_type END
);


-- ---------------------------------------------------------------------
-- 17d. BATCH_RUN_LOG - one row per batch run
-- A row left at RUNNING means the job died mid-way.
-- ---------------------------------------------------------------------
CREATE TABLE batch_run_log (
    run_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                     CONSTRAINT batch_run_log_pk PRIMARY KEY,
    job_name         VARCHAR2(50)  NOT NULL,
    started_on       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    finished_on      TIMESTAMP,
    status           VARCHAR2(20)  DEFAULT ON NULL 'RUNNING' NOT NULL
                     CONSTRAINT brl_status_chk CHECK (status IN ('RUNNING','SUCCEEDED','FAILED')),
    policies_scored  NUMBER,
    new_high_risk    NUMBER,
    promises_broken  NUMBER,
    notices_created  NUMBER,
    error_message    VARCHAR2(4000)
);


-- ---------------------------------------------------------------------
-- 18a. COLLECTIONS_PKG spec (replaces the Phase 3 spec)
-- ---------------------------------------------------------------------
CREATE OR REPLACE PACKAGE collections_pkg AS
    c_notice_gap_days CONSTANT PLS_INTEGER  := 14;
    c_job_nightly     CONSTANT VARCHAR2(50) := 'NIGHTLY_COLLECTIONS';

    -- Phase 3
    FUNCTION risk_score (p_policy_id IN VARCHAR2) RETURN NUMBER;

    FUNCTION risk_band (p_score IN NUMBER) RETURN VARCHAR2;

    PROCEDURE generate_dunning_notices (
        p_as_of           IN  DATE DEFAULT TRUNC(SYSDATE),
        p_notices_created OUT NUMBER
    );

    -- Phase 4
    PROCEDURE snapshot_risk_scores (
        p_as_of           IN  DATE DEFAULT TRUNC(SYSDATE),
        p_policies_scored OUT NUMBER
    );

    PROCEDURE flag_new_high_risk (
        p_as_of          IN  DATE DEFAULT TRUNC(SYSDATE),
        p_alerts_created OUT NUMBER
    );

    PROCEDURE flag_broken_promises (
        p_as_of          IN  DATE DEFAULT TRUNC(SYSDATE),
        p_alerts_created OUT NUMBER
    );

    PROCEDURE run_nightly_batch (p_as_of IN DATE DEFAULT TRUNC(SYSDATE));

    PROCEDURE acknowledge_alert (p_alert_id IN NUMBER);
END collections_pkg;


-- ---------------------------------------------------------------------
-- 18b. COLLECTIONS_PKG body (replaces the Phase 3 body)
-- ---------------------------------------------------------------------
CREATE OR REPLACE PACKAGE BODY collections_pkg AS

    ------------------------------------------------------------------
    -- Private helpers
    ------------------------------------------------------------------
    FUNCTION notice_text (
        p_level     IN PLS_INTEGER,
        p_policy_id IN VARCHAR2,
        p_amount    IN NUMBER
    ) RETURN VARCHAR2 IS
        l_amount VARCHAR2(30) := TRIM(TO_CHAR(p_amount, 'FML999G999G990D00'));
    BEGIN
        RETURN CASE p_level
            WHEN 1 THEN 'First notice: policy ' || p_policy_id || ' has an unpaid balance of '
                        || l_amount || '. Please contact us to arrange payment.'
            WHEN 2 THEN 'Second notice: the balance of ' || l_amount || ' on policy ' || p_policy_id
                        || ' remains unpaid. Please pay within 14 days to avoid further collection activity.'
            ELSE        'Final notice: the balance of ' || l_amount || ' on policy ' || p_policy_id
                        || ' is seriously past due. If we do not hear from you within 14 days, '
                        || 'this account may be referred to an outside collection agency.'
        END;
    END notice_text;


    -- Autonomous transactions: these commit on their own, so the run log
    -- survives even if the batch fails and rolls back its work.
    FUNCTION log_run_start (p_job_name IN VARCHAR2) RETURN NUMBER IS
        PRAGMA AUTONOMOUS_TRANSACTION;
        l_run_id NUMBER;
    BEGIN
        INSERT INTO batch_run_log (job_name, status)
        VALUES (p_job_name, 'RUNNING')
        RETURNING run_id INTO l_run_id;
        COMMIT;
        RETURN l_run_id;
    END log_run_start;


    PROCEDURE log_run_finish (
        p_run_id          IN NUMBER,
        p_status          IN VARCHAR2,
        p_policies_scored IN NUMBER   DEFAULT NULL,
        p_new_high_risk   IN NUMBER   DEFAULT NULL,
        p_promises_broken IN NUMBER   DEFAULT NULL,
        p_notices_created IN NUMBER   DEFAULT NULL,
        p_error_message   IN VARCHAR2 DEFAULT NULL
    ) IS
        PRAGMA AUTONOMOUS_TRANSACTION;
    BEGIN
        UPDATE batch_run_log
        SET    finished_on     = SYSTIMESTAMP,
               status          = p_status,
               policies_scored = p_policies_scored,
               new_high_risk   = p_new_high_risk,
               promises_broken = p_promises_broken,
               notices_created = p_notices_created,
               error_message   = SUBSTR(p_error_message, 1, 4000)
        WHERE  run_id = p_run_id;
        COMMIT;
    END log_run_finish;


    ------------------------------------------------------------------
    -- Phase 3: risk scoring and dunning
    ------------------------------------------------------------------
    FUNCTION risk_score (p_policy_id IN VARCHAR2) RETURN NUMBER IS
        l_tier        policies.score_tier%TYPE;
        l_plan        policies.payment_plan%TYPE;
        l_autopay     VARCHAR2(1);
        l_tenure      policies.tenure_years%TYPE;
        l_written_off NUMBER;
        l_outcome     VARCHAR2(30);
        l_status      VARCHAR2(20);
        l_score       NUMBER := 0;
    BEGIN
        SELECT p.score_tier,
               p.payment_plan,
               CASE WHEN p.autopay_flag THEN 'Y' ELSE 'N' END,
               p.tenure_years,
               q.written_off_amt,
               q.last_outcome,
               q.queue_status
        INTO   l_tier, l_plan, l_autopay, l_tenure,
               l_written_off, l_outcome, l_status
        FROM   policies p
               JOIN collections_queue_v q ON q.policy_id = p.policy_id
        WHERE  p.policy_id = p_policy_id;

        IF l_status = 'CLOSED' THEN
            RETURN 0;
        END IF;

        l_score := l_score + CASE l_tier WHEN 'A' THEN 5 WHEN 'B' THEN 15
                                         WHEN 'C' THEN 25 ELSE 35 END;
        l_score := l_score + CASE l_plan WHEN 'MONTHLY' THEN 10
                                         WHEN 'QUARTERLY' THEN 5 ELSE 0 END;
        IF l_autopay = 'N' THEN l_score := l_score + 10; END IF;
        IF l_tenure < 2    THEN l_score := l_score + 5;  END IF;

        l_score := l_score + CASE WHEN l_written_off >= 1000 THEN 15
                                  WHEN l_written_off >= 300  THEN 10
                                  WHEN l_written_off >  0    THEN 5
                                  ELSE 0 END;

        l_score := l_score + CASE WHEN l_outcome IS NULL            THEN 5
                                  WHEN l_outcome = 'REFUSED'        THEN 20
                                  WHEN l_outcome = 'DISPUTED'       THEN 15
                                  WHEN l_outcome = 'NO_CONTACT'     THEN 10
                                  WHEN l_outcome = 'LEFT_MESSAGE'   THEN 5
                                  WHEN l_outcome = 'PROMISE_TO_PAY' THEN -10
                                  ELSE 0 END;
        IF l_status = 'FOLLOW_UP_DUE' THEN l_score := l_score + 5; END IF;

        RETURN GREATEST(0, LEAST(100, l_score));
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN NULL;
    END risk_score;


    FUNCTION risk_band (p_score IN NUMBER) RETURN VARCHAR2 IS
    BEGIN
        RETURN CASE WHEN p_score IS NULL THEN NULL
                    WHEN p_score >= 60   THEN 'HIGH'
                    WHEN p_score >= 35   THEN 'MEDIUM'
                    ELSE 'LOW' END;
    END risk_band;


    PROCEDURE generate_dunning_notices (
        p_as_of           IN  DATE DEFAULT TRUNC(SYSDATE),
        p_notices_created OUT NUMBER
    ) IS
        l_level PLS_INTEGER;
        l_score NUMBER;
        l_text  VARCHAR2(2000);
    BEGIN
        p_notices_created := 0;

        FOR r IN (
            SELECT q.policy_id,
                   q.written_off_amt,
                   NVL(MAX(n.notice_level), 0) AS last_level,
                   MAX(n.notice_date)          AS last_notice_date
            FROM   collections_queue_v q
                   LEFT JOIN dunning_notices n ON n.policy_id = q.policy_id
            WHERE  q.recovery_status = 'WRITTEN_OFF'
            AND    q.queue_status   <> 'CLOSED'
            AND    NOT (NVL(q.last_outcome, 'NONE') = 'PROMISE_TO_PAY'
                        AND NVL(q.next_follow_up, p_as_of - 1) >= p_as_of)
            GROUP  BY q.policy_id, q.written_off_amt
        ) LOOP
            IF r.last_level < 3
               AND (r.last_notice_date IS NULL
                    OR r.last_notice_date <= p_as_of - c_notice_gap_days)
            THEN
                l_level := r.last_level + 1;
                l_score := risk_score(r.policy_id);
                l_text  := notice_text(l_level, r.policy_id, r.written_off_amt);

                INSERT INTO dunning_notices
                       (policy_id, notice_level, notice_date, amount_due, risk_score, notice_text)
                VALUES (r.policy_id, l_level, p_as_of, r.written_off_amt, l_score, l_text);

                p_notices_created := p_notices_created + 1;
            END IF;
        END LOOP;
    END generate_dunning_notices;


    ------------------------------------------------------------------
    -- Phase 4: nightly batch steps
    ------------------------------------------------------------------
    PROCEDURE snapshot_risk_scores (
        p_as_of           IN  DATE DEFAULT TRUNC(SYSDATE),
        p_policies_scored OUT NUMBER
    ) IS
    BEGIN
        -- MERGE makes the step safe to rerun: same day = update, not duplicate
        MERGE INTO risk_score_history h
        USING (
            SELECT policy_id,
                   collections_pkg.risk_score(policy_id) AS risk_score
            FROM   collections_queue_v
        ) s
        ON (h.snapshot_date = p_as_of AND h.policy_id = s.policy_id)
        WHEN MATCHED THEN UPDATE
            SET h.risk_score = s.risk_score,
                h.risk_band  = collections_pkg.risk_band(s.risk_score)
        WHEN NOT MATCHED THEN INSERT (snapshot_date, policy_id, risk_score, risk_band)
            VALUES (p_as_of, s.policy_id, s.risk_score, collections_pkg.risk_band(s.risk_score));

        p_policies_scored := SQL%ROWCOUNT;
    END snapshot_risk_scores;


    PROCEDURE flag_new_high_risk (
        p_as_of          IN  DATE DEFAULT TRUNC(SYSDATE),
        p_alerts_created OUT NUMBER
    ) IS
    BEGIN
        -- Only fires on a change: HIGH today, not HIGH in the most recent
        -- earlier snapshot. The first-ever run has no earlier snapshot,
        -- so it sets a baseline and flags nothing.
        INSERT INTO collection_alerts (policy_id, alert_type, alert_text)
        SELECT t.policy_id,
               'NEW_HIGH_RISK',
               'Risk rose to HIGH (' || t.risk_score || ') from '
               || prev.risk_band || ' (' || prev.risk_score || ').'
        FROM   risk_score_history t
               JOIN risk_score_history prev
                 ON  prev.policy_id     = t.policy_id
                 AND prev.snapshot_date = (SELECT MAX(x.snapshot_date)
                                           FROM   risk_score_history x
                                           WHERE  x.policy_id     = t.policy_id
                                           AND    x.snapshot_date < p_as_of)
        WHERE  t.snapshot_date = p_as_of
        AND    t.risk_band     = 'HIGH'
        AND    prev.risk_band <> 'HIGH'
        -- skip if already open, or already raised today (even if acknowledged),
        -- so same-day reruns don't re-alert
        AND    NOT EXISTS (SELECT 1
                           FROM   collection_alerts a
                           WHERE  a.policy_id  = t.policy_id
                           AND    a.alert_type = 'NEW_HIGH_RISK'
                           AND   (a.status = 'OPEN' OR a.created_on >= p_as_of));

        p_alerts_created := SQL%ROWCOUNT;
    END flag_new_high_risk;


    PROCEDURE flag_broken_promises (
        p_as_of          IN  DATE DEFAULT TRUNC(SYSDATE),
        p_alerts_created OUT NUMBER
    ) IS
    BEGIN
        -- Latest contact is a promise and the promise date has passed.
        -- Skip if this promise was already flagged (alert created after the
        -- promise was logged), even if that alert was acknowledged.
        INSERT INTO collection_alerts (policy_id, alert_type, alert_text)
        SELECT a.policy_id,
               'PROMISE_BROKEN',
               'Promise of ' || TRIM(TO_CHAR(a.promise_amount, 'FML999G999G990D00'))
               || ' due ' || TO_CHAR(a.promise_date, 'Mon DD, YYYY') || ' was not kept.'
        FROM  (
            SELECT ca.*,
                   ROW_NUMBER() OVER (PARTITION BY ca.policy_id
                                      ORDER BY ca.action_date DESC, ca.action_id DESC) AS rn
            FROM   collection_actions ca
        ) a
        WHERE  a.rn           = 1
        AND    a.outcome      = 'PROMISE_TO_PAY'
        AND    a.promise_date < p_as_of
        AND    NOT EXISTS (SELECT 1
                           FROM   collection_alerts x
                           WHERE  x.policy_id  = a.policy_id
                           AND    x.alert_type = 'PROMISE_BROKEN'
                           AND    x.created_on >= a.created_on);

        p_alerts_created := SQL%ROWCOUNT;
    END flag_broken_promises;


    PROCEDURE run_nightly_batch (p_as_of IN DATE DEFAULT TRUNC(SYSDATE)) IS
        l_run_id          NUMBER;
        l_policies_scored NUMBER;
        l_new_high_risk   NUMBER;
        l_promises_broken NUMBER;
        l_notices_created NUMBER;
    BEGIN
        l_run_id := log_run_start(c_job_nightly);

        snapshot_risk_scores    (p_as_of, l_policies_scored);
        flag_new_high_risk      (p_as_of, l_new_high_risk);
        flag_broken_promises    (p_as_of, l_promises_broken);
        generate_dunning_notices(p_as_of, l_notices_created);

        COMMIT;

        log_run_finish(l_run_id, 'SUCCEEDED',
                       l_policies_scored, l_new_high_risk,
                       l_promises_broken, l_notices_created);
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;   -- undo the batch's partial work...
            log_run_finish(l_run_id, 'FAILED',
                           p_error_message => SQLERRM || ' | '
                                              || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
            RAISE;      -- ...but still let the caller know it failed
    END run_nightly_batch;


    PROCEDURE acknowledge_alert (p_alert_id IN NUMBER) IS
    BEGIN
        UPDATE collection_alerts
        SET    status          = 'ACKNOWLEDGED',
               acknowledged_by = COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER),
               acknowledged_on = SYSDATE
        WHERE  alert_id = p_alert_id
        AND    status   = 'OPEN';
    END acknowledge_alert;

END collections_pkg;


