-- Baseline snapshot dated yesterday (gives the new-high check something
-- to compare against on the first run):
DECLARE
    l_count NUMBER;
BEGIN
    collections_pkg.snapshot_risk_scores(TRUNC(SYSDATE) - 1, l_count);
    DBMS_OUTPUT.PUT_LINE(l_count || ' policies scored for yesterday');
END;

-- Run the full batch:
BEGIN
    collections_pkg.run_nightly_batch;
END;

-- Run history (sort by start time, not run_id; identity values are
-- cached in blocks, so IDs can jump or appear out of order):
SELECT run_id, started_on, status, policies_scored,
       new_high_risk, promises_broken, notices_created, error_message
FROM   batch_run_log
ORDER  BY started_on DESC;

-- Alerts by type and status:
SELECT alert_type, status, COUNT(*)
FROM   collection_alerts
GROUP  BY alert_type, status
ORDER  BY alert_type, status;
