-- ---------------------------------------------------------------------
-- 13a. COLLECTION_ACTIONS_AUDIT - before/after history of every change
-- No foreign key to COLLECTION_ACTIONS on purpose: audit rows must
-- survive when the action they describe is deleted.
-- ---------------------------------------------------------------------
CREATE TABLE collection_actions_audit (
    audit_id            NUMBER GENERATED ALWAYS AS IDENTITY
                        CONSTRAINT collection_actions_audit_pk PRIMARY KEY,
    action_id           NUMBER        NOT NULL,
    policy_id           VARCHAR2(20),
    operation           VARCHAR2(10)  NOT NULL
                        CONSTRAINT caa_op_chk CHECK (operation IN ('INSERT','UPDATE','DELETE')),
    changed_by          VARCHAR2(255) NOT NULL,
    changed_on          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    old_outcome         VARCHAR2(30),
    new_outcome         VARCHAR2(30),
    old_promise_date    DATE,
    new_promise_date    DATE,
    old_promise_amount  NUMBER(10,2),
    new_promise_amount  NUMBER(10,2),
    old_next_follow_up  DATE,
    new_next_follow_up  DATE,
    old_notes           VARCHAR2(1000),
    new_notes           VARCHAR2(1000)
);


-- ---------------------------------------------------------------------
-- 13b. Audit trigger - one audit row per inserted/updated/deleted action
-- :OLD is empty on insert and :NEW is empty on delete, hence the NVLs.
-- ---------------------------------------------------------------------
CREATE OR REPLACE TRIGGER collection_actions_aud_trg
AFTER INSERT OR UPDATE OR DELETE ON collection_actions
FOR EACH ROW
DECLARE
    l_operation VARCHAR2(10);
BEGIN
    l_operation := CASE
                       WHEN INSERTING THEN 'INSERT'
                       WHEN UPDATING  THEN 'UPDATE'
                       ELSE 'DELETE'
                   END;

    INSERT INTO collection_actions_audit (
        action_id, policy_id, operation, changed_by,
        old_outcome,        new_outcome,
        old_promise_date,   new_promise_date,
        old_promise_amount, new_promise_amount,
        old_next_follow_up, new_next_follow_up,
        old_notes,          new_notes
    ) VALUES (
        NVL(:NEW.action_id, :OLD.action_id),
        NVL(:NEW.policy_id, :OLD.policy_id),
        l_operation,
        COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER),
        :OLD.outcome,        :NEW.outcome,
        :OLD.promise_date,   :NEW.promise_date,
        :OLD.promise_amount, :NEW.promise_amount,
        :OLD.next_follow_up, :NEW.next_follow_up,
        :OLD.notes,          :NEW.notes
    );
END;


-- ---------------------------------------------------------------------
-- 14. DUNNING_NOTICES - escalating notices (1st, 2nd, final)
-- The unique key on (policy_id, notice_level) is the database-level
-- guarantee that a policy never gets the same notice twice.
-- ---------------------------------------------------------------------
CREATE TABLE dunning_notices (
    notice_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                  CONSTRAINT dunning_notices_pk PRIMARY KEY,
    policy_id     VARCHAR2(20) NOT NULL
                  CONSTRAINT dn_policy_fk REFERENCES policies (policy_id),
    notice_level  NUMBER(1) NOT NULL
                  CONSTRAINT dn_level_chk CHECK (notice_level BETWEEN 1 AND 3),
    notice_date   DATE DEFAULT ON NULL TRUNC(SYSDATE) NOT NULL,
    amount_due    NUMBER(10,2),
    risk_score    NUMBER(3),
    notice_text   VARCHAR2(2000),
    status        VARCHAR2(20) DEFAULT ON NULL 'GENERATED'
                  CONSTRAINT dn_status_chk CHECK (status IN ('GENERATED','SENT','CANCELLED')),
    created_by    VARCHAR2(255) DEFAULT ON NULL
                  COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER),
    created_on    DATE DEFAULT ON NULL SYSDATE,
    CONSTRAINT dn_policy_level_uk UNIQUE (policy_id, notice_level)
);


-- ---------------------------------------------------------------------
-- 15a. COLLECTIONS_PKG spec - the public interface APEX calls
-- ---------------------------------------------------------------------
CREATE OR REPLACE PACKAGE collections_pkg AS
    c_notice_gap_days CONSTANT PLS_INTEGER := 14;

    FUNCTION risk_score (p_policy_id IN VARCHAR2) RETURN NUMBER;

    FUNCTION risk_band (p_score IN NUMBER) RETURN VARCHAR2;

    PROCEDURE generate_dunning_notices (
        p_as_of           IN  DATE DEFAULT TRUNC(SYSDATE),
        p_notices_created OUT NUMBER
    );
END collections_pkg;


-- ---------------------------------------------------------------------
-- 15b. COLLECTIONS_PKG body
-- Risk score (0-100) = tier (35) + plan (10) + no autopay (10)
--   + tenure < 2 yrs (5) + balance (15) + last outcome (20) + overdue (5).
--   Closed accounts score 0; a promise to pay subtracts 10.
-- Dunning rules: written-off balances only, skip closed accounts,
--   honor active promises, at most one notice per 14 days, max level 3.
-- ---------------------------------------------------------------------
CREATE OR REPLACE PACKAGE BODY collections_pkg AS

    -- Private helper: not in the spec, so only this package can call it.
    -- (Private functions can't be called from SQL, so callers compute
    -- the text in PL/SQL before the INSERT.)
    FUNCTION notice_text (
        p_level     IN PLS_INTEGER,
        p_policy_id IN VARCHAR2,
        p_amount    IN NUMBER
    ) RETURN VARCHAR2 IS
        l_amount VARCHAR2(30) := TRIM(TO_CHAR(p_amount, 'FML999G999G990D00'));
    BEGIN
        RETURN CASE p_level
            WHEN 1 THEN 'First notice: policy ' || p_policy_id || ' has an unpaid balance of '
                        || l_amount || '. Please contact us to arrange payment.'
            WHEN 2 THEN 'Second notice: the balance of ' || l_amount || ' on policy ' || p_policy_id
                        || ' remains unpaid. Please pay within 14 days to avoid further collection activity.'
            ELSE        'Final notice: the balance of ' || l_amount || ' on policy ' || p_policy_id
                        || ' is seriously past due. If we do not hear from you within 14 days, '
                        || 'this account may be referred to an outside collection agency.'
        END;
    END notice_text;


    FUNCTION risk_score (p_policy_id IN VARCHAR2) RETURN NUMBER IS
        l_tier        policies.score_tier%TYPE;
        l_plan        policies.payment_plan%TYPE;
        l_autopay     VARCHAR2(1);
        l_tenure      policies.tenure_years%TYPE;
        l_written_off NUMBER;
        l_outcome     VARCHAR2(30);
        l_status      VARCHAR2(20);
        l_score       NUMBER := 0;
    BEGIN
        SELECT p.score_tier,
               p.payment_plan,
               CASE WHEN p.autopay_flag THEN 'Y' ELSE 'N' END,
               p.tenure_years,
               q.written_off_amt,
               q.last_outcome,
               q.queue_status
        INTO   l_tier, l_plan, l_autopay, l_tenure,
               l_written_off, l_outcome, l_status
        FROM   policies p
               JOIN collections_queue_v q ON q.policy_id = p.policy_id
        WHERE  p.policy_id = p_policy_id;

        IF l_status = 'CLOSED' THEN
            RETURN 0;
        END IF;

        -- Who the customer is
        l_score := l_score + CASE l_tier WHEN 'A' THEN 5 WHEN 'B' THEN 15
                                         WHEN 'C' THEN 25 ELSE 35 END;
        l_score := l_score + CASE l_plan WHEN 'MONTHLY' THEN 10
                                         WHEN 'QUARTERLY' THEN 5 ELSE 0 END;
        IF l_autopay = 'N' THEN l_score := l_score + 10; END IF;
        IF l_tenure < 2    THEN l_score := l_score + 5;  END IF;

        -- How much is at stake
        l_score := l_score + CASE WHEN l_written_off >= 1000 THEN 15
                                  WHEN l_written_off >= 300  THEN 10
                                  WHEN l_written_off >  0    THEN 5
                                  ELSE 0 END;

        -- What collections has learned so far
        l_score := l_score + CASE WHEN l_outcome IS NULL            THEN 5
                                  WHEN l_outcome = 'REFUSED'        THEN 20
                                  WHEN l_outcome = 'DISPUTED'       THEN 15
                                  WHEN l_outcome = 'NO_CONTACT'     THEN 10
                                  WHEN l_outcome = 'LEFT_MESSAGE'   THEN 5
                                  WHEN l_outcome = 'PROMISE_TO_PAY' THEN -10
                                  ELSE 0 END;
        IF l_status = 'FOLLOW_UP_DUE' THEN l_score := l_score + 5; END IF;

        RETURN GREATEST(0, LEAST(100, l_score));
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN NULL;   -- policy isn't in the collections queue
    END risk_score;


    FUNCTION risk_band (p_score IN NUMBER) RETURN VARCHAR2 IS
    BEGIN
        RETURN CASE WHEN p_score IS NULL THEN NULL
                    WHEN p_score >= 60   THEN 'HIGH'
                    WHEN p_score >= 35   THEN 'MEDIUM'
                    ELSE 'LOW' END;
    END risk_band;


    PROCEDURE generate_dunning_notices (
        p_as_of           IN  DATE DEFAULT TRUNC(SYSDATE),
        p_notices_created OUT NUMBER
    ) IS
        l_level PLS_INTEGER;
        l_score NUMBER;
        l_text  VARCHAR2(2000);
    BEGIN
        p_notices_created := 0;

        FOR r IN (
            SELECT q.policy_id,
                   q.written_off_amt,
                   NVL(MAX(n.notice_level), 0) AS last_level,
                   MAX(n.notice_date)          AS last_notice_date
            FROM   collections_queue_v q
                   LEFT JOIN dunning_notices n ON n.policy_id = q.policy_id
            WHERE  q.recovery_status = 'WRITTEN_OFF'
            AND    q.queue_status   <> 'CLOSED'
            -- respect an active promise to pay (NVL guards against NULLs
            -- for never-contacted policies; without it, NOT(NULL) drops them)
            AND    NOT (NVL(q.last_outcome, 'NONE') = 'PROMISE_TO_PAY'
                        AND NVL(q.next_follow_up, p_as_of - 1) >= p_as_of)
            GROUP  BY q.policy_id, q.written_off_amt
        ) LOOP
            IF r.last_level < 3
               AND (r.last_notice_date IS NULL
                    OR r.last_notice_date <= p_as_of - c_notice_gap_days)
            THEN
                l_level := r.last_level + 1;
                l_score := risk_score(r.policy_id);
                l_text  := notice_text(l_level, r.policy_id, r.written_off_amt);

                INSERT INTO dunning_notices
                       (policy_id, notice_level, notice_date, amount_due, risk_score, notice_text)
                VALUES (r.policy_id, l_level, p_as_of, r.written_off_amt, l_score, l_text);

                p_notices_created := p_notices_created + 1;
            END IF;
        END LOOP;
    END generate_dunning_notices;

END collections_pkg;


