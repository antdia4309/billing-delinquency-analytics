SELECT policy_id,
       collections_pkg.risk_score(policy_id)                            AS score,
       collections_pkg.risk_band(collections_pkg.risk_score(policy_id)) AS band
FROM   collections_queue_v
ORDER  BY 2 DESC NULLS LAST
FETCH FIRST 10 ROWS ONLY;

-- Generate notices (run twice: the second run should create 0):
DECLARE
    l_count NUMBER;
BEGIN
    collections_pkg.generate_dunning_notices(p_notices_created => l_count);
    DBMS_OUTPUT.PUT_LINE(l_count || ' notices created');
END;

-- Simulate two weeks later to see escalation (then DELETE FROM dunning_notices
-- and rerun the block above to return to a realistic state):
