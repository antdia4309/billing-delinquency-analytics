-- ---------------------------------------------------------------------
-- 9a. Unique key on POLICIES.POLICY_ID
-- Data Workshop gave POLICIES its own surrogate primary key, so a
-- foreign key needs a unique constraint on POLICY_ID to point at.
-- ---------------------------------------------------------------------
ALTER TABLE policies ADD CONSTRAINT policies_policy_id_uk UNIQUE (policy_id);


-- ---------------------------------------------------------------------
-- 9b. COLLECTION_ACTIONS - one row per contact attempt
-- Check constraints are the database backstop; APEX validations on
-- pages 6 and 7 give users friendly messages first.
-- CREATED_BY / CREATED_ON are filled by the database (DEFAULT ON NULL),
-- so the APEX columns are Query Only.
-- ---------------------------------------------------------------------
CREATE TABLE collection_actions (
    action_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                    CONSTRAINT collection_actions_pk PRIMARY KEY,
    policy_id       VARCHAR2(20) NOT NULL
                    CONSTRAINT ca_policy_fk REFERENCES policies (policy_id),
    action_date     DATE DEFAULT ON NULL SYSDATE NOT NULL,
    action_type     VARCHAR2(20) NOT NULL
                    CONSTRAINT ca_type_chk CHECK (action_type IN ('CALL','EMAIL','LETTER','TEXT')),
    outcome         VARCHAR2(30) NOT NULL
                    CONSTRAINT ca_outcome_chk CHECK (outcome IN
                      ('NO_CONTACT','LEFT_MESSAGE','SPOKE_TO_INSURED',
                       'PROMISE_TO_PAY','PAYMENT_RECEIVED','DISPUTED','REFUSED')),
    promise_date    DATE,
    promise_amount  NUMBER(10,2),
    next_follow_up  DATE,
    notes           VARCHAR2(1000),
    created_by      VARCHAR2(255) DEFAULT ON NULL
                    COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER),
    created_on      DATE DEFAULT ON NULL SYSDATE,
    CONSTRAINT ca_promise_chk CHECK (
        outcome <> 'PROMISE_TO_PAY'
        OR (promise_date IS NOT NULL AND promise_amount > 0))
);

CREATE INDEX collection_actions_policy_ix ON collection_actions (policy_id);


-- ---------------------------------------------------------------------
-- 10. COLLECTIONS_QUEUE_V - one row per policy with a missed payment
-- Latest action per policy via KEEP (DENSE_RANK LAST ...).
-- QUEUE_PRIORITY drives the work-queue sort (overdue first), since an
-- alphabetical sort on QUEUE_STATUS would put CLOSED on top.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW collections_queue_v AS
WITH missed AS (
    SELECT policy_id,
           due_date        AS missed_due_date,
           amount_due      AS missed_amount,
           written_off_amt
    FROM   installments
    WHERE  installment_status = 'MISSED'
),
last_action AS (
    SELECT policy_id,
           COUNT(*)                                                                    AS action_count,
           MAX(action_date)                                                            AS last_action_date,
           MAX(outcome)        KEEP (DENSE_RANK LAST ORDER BY action_date, action_id)  AS last_outcome,
           MAX(next_follow_up) KEEP (DENSE_RANK LAST ORDER BY action_date, action_id)  AS next_follow_up
    FROM   collection_actions
    GROUP  BY policy_id
),
base AS (
    SELECT p.policy_id,
           p.state_code,
           p.payment_plan,
           p.score_tier,
           p.cancel_date,
           m.missed_due_date,
           m.missed_amount,
           m.written_off_amt,
           CASE WHEN m.written_off_amt > 0 THEN 'WRITTEN_OFF' ELSE 'RECOVERED' END AS recovery_status,
           NVL(a.action_count, 0)                                               AS action_count,
           a.last_action_date,
           a.last_outcome,
           a.next_follow_up,
           CASE
               WHEN a.last_outcome = 'PAYMENT_RECEIVED'  THEN 'CLOSED'
               WHEN a.action_count IS NULL              THEN 'NEW'
               WHEN a.next_follow_up <= TRUNC(SYSDATE)  THEN 'FOLLOW_UP_DUE'
               ELSE 'IN_PROGRESS'
           END                                                                  AS queue_status
    FROM   policies p
           JOIN missed m           ON m.policy_id = p.policy_id
           LEFT JOIN last_action a ON a.policy_id = p.policy_id
)
SELECT b.*,
       CASE queue_status
            WHEN 'FOLLOW_UP_DUE' THEN 1
            WHEN 'NEW'           THEN 2
            WHEN 'IN_PROGRESS'   THEN 3
            ELSE 4
       END AS queue_priority
FROM   base b;


-- ---------------------------------------------------------------------
-- 11. Page 6/7 validations (APEX PL/SQL Expressions)
-- Grid values arrive as formatted text, so amounts are stripped of
-- '$' and ',' and dates are parsed with the column format mask.
-- Page 7 uses the same logic with :P7_ item names.
-- ---------------------------------------------------------------------
-- Promise requires date and amount:
--   NVL(:OUTCOME, 'X') <> 'PROMISE_TO_PAY'
--   OR (:PROMISE_DATE IS NOT NULL
--       AND TO_NUMBER(REPLACE(REPLACE(:PROMISE_AMOUNT, '$'), ',')) > 0)
--
-- Promise date after contact:
--   :PROMISE_DATE IS NULL
--   OR TO_DATE(:PROMISE_DATE, 'Mon DD, YYYY') >= TO_DATE(:ACTION_DATE, 'Mon DD, YYYY')


-- ---------------------------------------------------------------------
-- 12. Optional seed data - sample activity on ~1/3 of the queue
-- ORA_HASH makes the selection repeatable. Rows are tagged SEED_DATA.
-- Remove with: DELETE FROM collection_actions WHERE created_by = 'SEED_DATA';
-- ---------------------------------------------------------------------
INSERT INTO collection_actions
       (policy_id, action_date, action_type, outcome,
        promise_date, promise_amount, next_follow_up, notes, created_by)
SELECT policy_id,
       TRUNC(SYSDATE) - d,
       CASE MOD(rn, 4) WHEN 0 THEN 'CALL' WHEN 1 THEN 'EMAIL'
                       WHEN 2 THEN 'LETTER' ELSE 'TEXT' END,
       outcome,
       CASE WHEN outcome = 'PROMISE_TO_PAY' THEN TRUNC(SYSDATE) - d + 7 END,
       CASE WHEN outcome = 'PROMISE_TO_PAY' THEN ROUND(missed_amount * 0.5, 2) END,
       CASE WHEN outcome <> 'PAYMENT_RECEIVED' THEN TRUNC(SYSDATE) - d + 10 END,
       'Seeded sample activity',
       'SEED_DATA'
FROM (
    SELECT policy_id, missed_amount,
           ROW_NUMBER() OVER (ORDER BY ORA_HASH(policy_id)) AS rn,
           MOD(ORA_HASH(policy_id, 1000), 30)                AS d,
           CASE MOD(ORA_HASH(policy_id, 97), 6)
                WHEN 0 THEN 'NO_CONTACT'       WHEN 1 THEN 'LEFT_MESSAGE'
                WHEN 2 THEN 'SPOKE_TO_INSURED' WHEN 3 THEN 'PROMISE_TO_PAY'
                WHEN 4 THEN 'PAYMENT_RECEIVED' ELSE 'DISPUTED'
           END                                               AS outcome
    FROM   collections_queue_v
    WHERE  action_count = 0
    AND    MOD(ORA_HASH(policy_id, 9), 3) = 0
);
